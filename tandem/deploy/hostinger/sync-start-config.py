#!/usr/bin/env python3
"""Keep Docker Manager's self-contained configs in sync with the source files."""
import argparse
from pathlib import Path

parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('--check', action='store_true', help='fail if inline configs need regeneration')
args = parser.parse_args()
root = Path(__file__).resolve().parents[2]
compose = root / 'deploy/hostinger/compose.yaml'
begin = '  # BEGIN GENERATED TANDEM START CONFIGS\n'
end = '  # END GENERATED TANDEM START CONFIGS\n'
blocks = [begin, '  # Generated by sync-start-config.py; edit the source page/policy instead.\n']
for key, path in [('tandem-start-policy', root / 'deploy/policies/tandem-start.json'),
                  ('tandem-start-page', root / 'start/index.html')]:
    # Compose interpolates dollar signs in content, including inline JavaScript.
    content = path.read_text().replace('$', '$$')
    blocks.append('  ' + key + ':\n    content: |\n')
    blocks.extend('      ' + line + '\n' if line else '\n' for line in content.splitlines())
blocks.append(end)
text = compose.read_text()
assert text.count(begin) == text.count(end) == 1, 'Missing or duplicate generated config markers'
start, finish = text.index(begin), text.index(end) + len(end)
updated = text[:start] + ''.join(blocks) + text[finish:]
if args.check:
    if updated != text:
        parser.exit(1, 'Start configs are stale; run python3 tandem/deploy/hostinger/sync-start-config.py\n')
    print('Hostinger start configs match source page and policy')
else:
    compose.write_text(updated)
